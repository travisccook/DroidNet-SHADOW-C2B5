#!/usr/bin/env python3
"""Freeze the pre-ShadowMap button tables into legacy_tables.h.

The legacy-equivalence test replays the old table-driven code (footButtonMappings /
domeButtonMappings plus the marcDuinoButtonPush switch) against the new resolver and
built-in defaults. Run from the repo root:

    python3 test/test_legacy_equivalence/make_legacy_tables.py <commit>

<commit> must be a revision from before the switch was removed (the header records it).
"""
import re
import subprocess
import sys

rev = sys.argv[1] if len(sys.argv) > 1 else "HEAD"
config = subprocess.check_output(["git", "show", f"{rev}:src/config.cpp"], text=True)
main = subprocess.check_output(["git", "show", f"{rev}:src/main.cpp"], text=True)
sha = subprocess.check_output(["git", "rev-parse", "--short", rev], text=True).strip()

def table(name):
    body = re.search(r"const SimpleButtonMapping %s\[\] = \{(.*?)\};" % name, config, re.S).group(1)
    return re.findall(r'\{\s*(\w+),\s*(\w+),\s*(\d+),\s*"[^"]*"\s*\}', body)

switch = main[main.index("void marcDuinoButtonPush"):]
switch = switch[: switch.index("// End Std Marcduino Function Calls")]
sends = {}
for m in re.finditer(r"case (\d+):(.*?)break;", switch, re.S):
    code, body = int(m.group(1)), m.group(2)
    prints = re.findall(r'Serial1\.print\("([^"]*)"\)', body)
    if "toSerial" in body or "volume" in body or "brightness" in body:
        sends[code] = None  # stateful volume/brightness, removed on purpose
    elif len(prints) == 1:
        sends[code] = prints[0]
    elif not prints:
        sends[code] = ""
    else:
        raise SystemExit(f"case {code} sends more than one line")

held = {"UP": "kHeldUp", "RIGHT": "kHeldRight", "DOWN": "kHeldDown", "LEFT": "kHeldLeft",
        "L3": "kHeldL3", "PS": "kHeldPs", "L1": "kHeldL1", "L2": "kHeldL2",
        "CIRCLE": "kHeldCircle", "CROSS": "kHeldCross", "NO_MODIFIER": "0"}

def c_str(s):
    return '"' + s + '"'  # already C source text, escapes included

out = [
    "// Generated by make_legacy_tables.py from src/config.cpp and src/main.cpp at %s." % sha,
    "// A frozen copy of the old button tables; do not edit.",
    "#pragma once",
    "#include <stdint.h>",
    "#include <sm_resolve.h>",
    "",
    "struct LegacyMapping {",
    "    uint16_t primary;   // HeldBit",
    "    uint16_t modifier;  // HeldBit, 0 = no modifier",
    "    const char *sent;   // exact bytes sent to Serial1, \"\" = nothing, nullptr = stateful (removed)",
    "};",
    "",
]
for name, var in (("footButtonMappings", "kLegacyFoot"), ("domeButtonMappings", "kLegacyDome")):
    out.append("const LegacyMapping %s[] = {" % var)
    for primary, modifier, code in table(name):
        code = int(code)
        sent = sends.get(code, "")
        text = "nullptr" if sent is None else c_str(sent)
        out.append("    {sm::%s, %s, %s},  // code %d" % (held[primary], ("sm::" + held[modifier]) if modifier != "NO_MODIFIER" else "0", text, code))
    out.append("};")
    out.append("")
open("test/test_legacy_equivalence/legacy_tables.h", "w").write("\n".join(out))
print("wrote legacy_tables.h from", sha)
